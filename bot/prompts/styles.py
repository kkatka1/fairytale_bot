def get_style_rules(style_key: str = "classic_russian") -> str:
    """
    Возвращает правила выбранного стиля сказки.
    Доступные стили:
    - classic_russian: Классическая русская детская сказка
    - european_magic: Европейская волшебная сказка
    - modern_adventure: Современная приключенческая сказка
    - bedtime_calm: Спокойная сказка перед сном
    """
    styles = {
        "classic_russian": """
Стиль: Классическая русская детская сказка
- простой язык;
- добрый юмор;
- ритмичность;
- повторяющиеся элементы;
- лёгкая мораль.
Не копировать стиль конкретных авторов. Не смешивать стили между собой.
""".strip(),
        "european_magic": """
Стиль: Европейская волшебная сказка
- атмосфера чуда;
- магический мир;
- путешествие героя;
- эмоциональная глубина.
Не копировать стиль конкретных авторов. Не смешивать стили между собой.
""".strip(),
        "modern_adventure": """
Стиль: Современная приключенческая сказка
- динамичный сюжет;
- дружба;
- исследование мира;
- юмор.
Не копировать стиль конкретных авторов. Не смешивать стили между собой.
""".strip(),
        "bedtime_calm": """
Стиль: Спокойная сказка перед сном
- мягкий темп;
- уютная атмосфера;
- ощущение безопасности.
Не копировать стиль конкретных авторов. Не смешивать стили между собой.
""".strip(),
    }

    return styles.get(style_key, styles["classic_russian"])
