def get_age_rules(child_age: str) -> str:
    """
    Возвращает правила генерации сказки по возрасту ребёнка.

    Возрастные группы:
    3-4 года
    5-6 лет
    7-9 лет

    Если возраст определить невозможно,
    используются универсальные правила.
    """

    age_text = child_age.lower().strip()

    age = None

    # Извлекаем возраст цифрами
    for part in age_text.replace(",", ".").split():
        try:
            age = float(part)
            break
        except ValueError:
            continue

    # Если возраст написан словами
    if age is None:
        words = {
            "три": 3,
            "четыре": 4,
            "пять": 5,
            "шесть": 6,
            "семь": 7,
            "восемь": 8,
            "девять": 9,
        }

        for word, value in words.items():
            if word in age_text:
                age = value
                break

    if age is None:
        return """
Правила для детской сказки:
- понятный и добрый сюжет;
- безопасная атмосфера;
- позитивные эмоции;
- интересное приключение;
- понятный финал.
""".strip()


    if 3 <= age <= 4:
        return """
Правила для возраста 3-4 года:

Ребёнок воспринимает мир через эмоции, образы и повторение.

Поэтому:
- использовать короткие понятные предложения;
- одно важное действие за один абзац;
- чаще обращаться к герою по имени;
- использовать повторяющиеся элементы;
- новых персонажей вводить постепенно;
- персонажей одновременно не больше 2-4;
- избегать сложных объяснений;
- добавлять звуки, движения и простые ощущения;
- сохранять ощущение безопасности;
- каждая сцена должна быть понятной ребёнку.

Главная эмоция:
чувство безопасности и радости.
""".strip()


    if 5 <= age <= 6:
        return """
Правила для возраста 5-6 лет:

Ребёнок уже понимает последовательность событий
и способен следить за развитием приключения.

Поэтому:
- главный герой должен принимать решения;
- допускаются небольшие загадки и открытия;
- можно добавлять больше персонажей;
- персонажи могут иметь разные характеры;
- допускается лёгкий юмор;
- приключение должно развиваться постепенно;
- герой должен чему-то научиться;
- мораль должна быть понятной через события, а не через объяснение.

Главная эмоция:
восхищение приключением и гордость за героя.
""".strip()


    if 7 <= age <= 9:
        return """
Правила для возраста 7-9 лет:

Ребёнок способен понимать более сложные сюжеты
и развитие характера героя.

Поэтому:
- допускаются тайны и неожиданные повороты;
- герой должен делать выбор;
- важны дружба, ответственность и развитие;
- персонажи могут ошибаться и меняться;
- допускаются несколько связанных событий;
- мораль должна естественно вытекать из истории;
- финал должен ощущаться завершённым.

Главная эмоция:
гордость за героя и его поступки.
""".strip()


    return """
Правила для детской сказки:
- добрый и понятный сюжет;
- безопасная атмосфера;
- положительные эмоции;
- интересное приключение;
- завершённый финал.
""".strip()