def get_age_rules(child_age: str) -> str:
    """
    Возвращает возрастные правила в зависимости от возраста ребёнка.
    Поддерживаемые группы: 3-4 года, 5-6 лет, 7-9 лет.
    Если возраст не попадает в категории, возвращаются универсальные мягкие правила.
    """
    age_str = child_age.lower().strip()

    # Определяем возрастную категорию
    if any(age in age_str for age in ["3", "четыр", "четыре", "три", "3-4"]):
        return """
Ребёнок этого возраста воспринимает мир эмоционально и образно.

Поэтому:
- предложения должны быть короткими;
- одно действие за один абзац;
- часто обращаться по имени ребёнка;
- использовать повторяющиеся фразы;
- персонажей не больше 2–4 одновременно;
- каждый новый персонаж должен сразу быть понятен;
- не использовать длинные объяснения;
- больше звуков ("бип-бип", "кап-кап", "тук-тук");
- больше действий;
- мир должен быть добрым и безопасным;
- каждые несколько абзацев должно происходить что-то интересное;
- финал должен дарить чувство спокойствия.

Главная эмоция — чувство безопасности.
""".strip()
    elif any(age in age_str for age in ["4", "5", "пять", "шесть", "5-6"]):
        return """
Правила для возраста 5-6 лет:
Ребёнок уже способен понимать причинно-следственные связи. Поэтому:
- герой принимает собственные решения; 
- допускаются небольшие загадки; 
- появляется чувство открытия нового; 
- допускается больше персонажей; 
- персонажи могут иметь разные характеры; 
- допускается лёгкий юмор; 
- приключение должно развиваться постепенно; 
- главный герой учится чему-то новому; 
- финал должен вызывать чувство гордости за героя.

Главная эмоция — восхищение приключением.
""".strip()
    elif any(age in age_str for age in ["6", "7", "8", "9", "семь", "восемь", "девять", "7-9"]):
        return """
Правила для возраста 7-9 лет:
Ребёнок способен понимать сложные отношения между героями.

Поэтому:
- допускаются несколько сюжетных линий;
- герой делает моральный выбор;
- допускаются тайны;
- появляются неожиданные повороты;
- дружба становится важной частью истории;
- персонажи могут ошибаться;
- герой развивается во время сказки;
- финал должен давать ощущение завершённого боль

Главная эмоция — гордость за себя и своих близких.

""".strip()
    else:
        # Универсальные мягкие правила по умолчанию для детской аудитории
        return """
Правила для детской сказки:
- понятный и добрый сюжет;
- увлекательные приключения;
- позитивные эмоции;
- безопасная атмосфера.
""".strip()
